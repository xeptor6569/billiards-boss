import { execSync } from 'child_process';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

// Get __dirname equivalent in ES modules
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Read package.json
const packageJson = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'package.json'), 'utf8'));

// Ensure the output directory exists
const outputDir = path.join(__dirname, '..', 'src', 'lib');
const outputPath = path.join(outputDir, 'build-info.ts');

// Ensure directory exists
if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

// Check for environment variables first (for Docker builds)
const buildNumberFromEnv = process.env.BUILD_NUMBER;
const commitHashFromEnv = process.env.COMMIT_HASH;

let buildNumber, commitHash;

if (buildNumberFromEnv && commitHashFromEnv) {
  // Use environment variables (from Docker build args)
  console.log('📦 Using build info from environment variables');
  buildNumber = buildNumberFromEnv;
  commitHash = commitHashFromEnv;
} else {
  // Try to get from git
  try {
    // 1. Get the Git Commit Count (Incremental Build Number)
    // This counts all commits in the current branch history
    buildNumber = execSync('git rev-list --count HEAD', { 
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore']
    }).trim();
    
    // 2. Get the Short Hash (For debugging, e.g., 'a1b2c3')
    commitHash = execSync('git rev-parse --short HEAD', {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore']
    }).trim();
    
    console.log(`✅ Build info generated from git: v${packageJson.version}.${buildNumber} (${commitHash})`);
  } catch (error) {
    console.warn('⚠️  Failed to generate build info from git:', error.message);
    console.log('📦 Using fallback build info (dev mode)');
    
    // Fallback for environments without git (like a clean docker context without .git)
    buildNumber = '0';
    commitHash = 'dev';
  }
}

// 3. Get the current date
const buildDate = new Date().toISOString();

// 4. Construct the file content
const content = `// This file is auto-generated by scripts/generate-build-id.mjs
// Do not edit this file manually - it will be overwritten on each build

export const BUILD_INFO = {
  version: "${packageJson.version}",
  buildNumber: ${buildNumber},
  commitHash: "${commitHash}",
  buildDate: "${buildDate}",
  display: "v${packageJson.version}.${buildNumber}",
} as const;
`;

// 5. Write to src/lib folder
fs.writeFileSync(outputPath, content, 'utf8');

if (!buildNumberFromEnv || !commitHashFromEnv) {
  console.log(`✅ Build info written: v${packageJson.version}.${buildNumber} (${commitHash})`);
}

